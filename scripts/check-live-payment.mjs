import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { ConvexHttpClient } from 'convex/browser';
import { chromium } from 'playwright';
import { api } from '../convex/_generated/api.js';

const local = await readFile('.env.local', 'utf8');
const url = local.split('\n').find(line => line.startsWith('NEXT_PUBLIC_CONVEX_URL=')).split('=')[1].trim();
assert.equal(url, 'https://qualified-bullfrog-386.convex.cloud', 'Development only');
const client = new ConvexHttpClient(url);
const email = `razorpay-live-check-${randomUUID()}@example.invalid`, password = randomUUID() + randomUUID();
const signedIn = await client.action(api.auth.signIn, { provider: 'password', params: { flow: 'signUp', email, password } });
assert.ok(signedIn.tokens?.token);
client.setAuth(signedIn.tokens.token);
const base = process.env.PAYMENT_TEST_URL || 'http://localhost:3000';
const headers = { Authorization: `Bearer ${signedIn.tokens.token}`, 'Content-Type': 'application/json' };
assert.equal((await fetch(`${base}/api/create-order`, { method: 'POST' })).status, 401);
assert.equal((await fetch(`${base}/api/verify-payment`, { method: 'POST', headers, body: '{}' })).status, 400);
const createdResponse = await fetch(`${base}/api/create-order`, { method: 'POST', headers, body: JSON.stringify({ amount: 1 }) });
const order = await createdResponse.json();
assert.equal(createdResponse.status, 200, JSON.stringify(order));
assert.equal(order.amount, 100, 'Backend ignores browser-supplied amount');
assert.equal(order.currency, 'INR');
assert.match(order.order_id, /^order_/);
assert.equal('key_secret' in order, false);
assert.match(order.key_id, /^rzp_test_/);
const rejected = await fetch(`${base}/api/verify-payment`, { method: 'POST', headers, body: JSON.stringify({ razorpay_order_id: order.order_id, razorpay_payment_id: 'pay_fake', razorpay_signature: '0'.repeat(64) }) });
assert.equal(rejected.status, 400);
assert.deepEqual(await client.query(api.payments.status, {}), { available: false });
let browser;
try {
  browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/app`);
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Pay ₹1.00', exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('iframe')].some(frame => /razorpay/.test(frame.src)), { timeout: 30000 });
  await page.locator('iframe').filter({ visible: true }).first().waitFor({ timeout: 30000 });
  const checkoutFrame = page.frames().find(frame => /razorpay/.test(frame.url()));
  assert.ok(checkoutFrame);
  await checkoutFrame.locator('input[type="tel"]').first().waitFor({ state: 'visible', timeout: 30000 });
  await page.screenshot({ path: '/tmp/charpai-razorpay-real-modal.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: real Razorpay test order created via authenticated endpoint; price tampering, missing fields and bad signature rejected; live Razorpay checkout modal opened. No payment submitted.');
} finally { await browser?.close(); }
