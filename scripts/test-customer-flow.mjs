// Development only; real Razorpay test checkout and real AI, fictional memories.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { ConvexHttpClient } from 'convex/browser';
import { api } from '../convex/_generated/api.js';
const base = 'http://localhost:3017';
assert.match(await readFile('.env.local','utf8'), /CONVEX_DEPLOYMENT=dev:qualified-bullfrog-386/);
const speech = 'This is a fictional family interview. My name is Kamala. I grew up in Mysuru. Every morning, my mother poured coffee into a copper tumbler. It had a rolled rim and a dent near the bottom. I would sit by the kitchen doorway holding that warm tumbler. I remember the smell of coffee and the sunlight on the floor. At school I had a wooden ruler. Its edge had small pencil marks. I used it to draw straight lines in my notebook. I kept it in my school bag for years. These two objects remind me of my childhood: the copper coffee tumbler and my wooden school ruler. I am sharing these memories with my granddaughter.';
execFileSync('say',['-o','/private/tmp/charpai-fiction.aiff',speech]);
const ffmpeg = (await import('ffmpeg-static')).default;
execFileSync(ffmpeg,['-y','-i','/private/tmp/charpai-fiction.aiff','-ac','1','-ar','44100','/private/tmp/charpai-fiction.wav'],{stdio:'ignore'});
const browser=await chromium.launch({args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--use-file-for-fake-audio-capture=/private/tmp/charpai-fiction.wav']});
try {
const context=await browser.newContext({permissions:['microphone'],acceptDownloads:true});
const page=await context.newPage();
const email=`customer-check-${randomUUID()}@example.invalid`,password=randomUUID()+randomUUID();
await writeFile('/private/tmp/charpai-customer-check.json',JSON.stringify({email,password}),{mode:0o600});
await page.goto(base+'/app/login');
await page.getByRole('button',{name:'Sign up',exact:true}).click();
await page.getByLabel('Email',{exact:true}).fill(email);
await page.getByLabel('Password',{exact:true}).fill(password);
await page.getByRole('button',{name:'Create account',exact:true}).click();
await page.getByRole('button',{name:'Pay ₹200.00',exact:true}).click();
const checkout=page.frameLocator('iframe.razorpay-checkout-frame');
await checkout.getByRole('button',{name:'Continue',exact:true}).waitFor();
await checkout.locator('input[type="tel"]').fill('9123456789');
if (await checkout.getByRole('button',{name:'Continue',exact:true}).count()) await checkout.getByRole('button',{name:'Continue',exact:true}).click({timeout:5000});
await checkout.getByText('Netbanking',{exact:true}).click({timeout:10000});
const bankPromise=context.waitForEvent('page');
await checkout.getByText('HDFC Bank',{exact:true}).first().click();
const bank=await bankPromise;
await bank.getByRole('button',{name:'Success',exact:true}).click();
await page.getByText('4 generation credits remaining.',{exact:false}).waitFor({timeout:45000});
console.log('PASS: real ₹200 Razorpay test payment unlocked four credits.');
const client=new ConvexHttpClient('https://qualified-bullfrog-386.convex.cloud');
const login=await client.action(api.auth.signIn,{provider:'password',params:{flow:'signIn',email,password}});
client.setAuth(login.tokens.token);
assert.equal((await client.query(api.payments.status,{})).credits,4);
await page.reload();
await page.getByRole('button',{name:'Start recording',exact:true}).click();
await page.getByRole('button',{name:'Stop and save',exact:true}).waitFor();
await page.waitForTimeout(49000);
await page.getByRole('button',{name:'Stop and save',exact:true}).click();
await page.getByRole('link',{name:'Download recording'}).waitFor();
console.log('PASS: recorded fictional spoken interview in the paid workspace.');
await page.getByRole('button',{name:'Generate preview',exact:true}).click();
await page.getByRole('button',{name:'Confirm changes',exact:true}).waitFor({timeout:300000});
assert.equal((await client.query(api.payments.status,{})).credits,3);
await page.screenshot({path:'/private/tmp/charpai-generated-review.png',fullPage:true});
console.log('PASS: real transcription and story generation; one credit used.');
await page.getByRole('button',{name:'Confirm changes',exact:true}).click();
await page.getByRole('button',{name:'Export PDF',exact:true}).waitFor({timeout:30000});
const stories=await client.query(api.storybookPages.listMine,{});
assert.equal(stories.length,1);
const story=await client.query(api.storybookPages.getPublicBySlug,{slug:stories[0].slug});
assert.ok(story.sections.every(section=>section.illustrationUrl),'Each section should have artwork');
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Export PDF',exact:true}).click();
await (await downloadPromise).saveAs('/private/tmp/charpai-customer-test.pdf');
await page.goto(base+'/s/'+stories[0].slug);
await page.getByText(story.title,{exact:true}).first().waitFor();
await page.screenshot({path:'/private/tmp/charpai-customer-story.png',fullPage:true});
assert.equal((await client.query(api.payments.status,{})).credits,3);
console.log('PASS: illustrated story saved, public reader opened, PDF exported; three credits retained.');
await writeFile('/private/tmp/charpai-customer-result.json',JSON.stringify({slug:stories[0].slug,sections:story.sections.length,credits:3}));
} finally {await browser.close();}
