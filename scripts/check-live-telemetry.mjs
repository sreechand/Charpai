import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { ConvexHttpClient } from 'convex/browser';
import { api } from '../convex/_generated/api.js';
const env = await readFile('.env.local', 'utf8');
const url = env.split('\n').find(line => line.startsWith('NEXT_PUBLIC_CONVEX_URL=')).slice('NEXT_PUBLIC_CONVEX_URL='.length).trim();
if (!env.includes('CONVEX_DEPLOYMENT=dev:qualified-bullfrog-386') || url !== 'https://qualified-bullfrog-386.convex.cloud') throw new Error('This check only runs against the named development database.');
const client = new ConvexHttpClient(url);
const signedIn = await client.action(api.auth.signIn, { provider: 'password', params: { flow: 'signUp', email: `telemetry-check-${randomUUID()}@example.invalid`, password: randomUUID() + randomUUID() } });
assert.ok(signedIn.tokens?.token, 'Test account sign-in must return a token');
client.setAuth(signedIn.tokens.token);
const generationId = 'verification-' + randomUUID();
const requestId = await client.mutation(api.telemetry.start, { generationId, stage: 'compose', promptVersion: 'verification-only' });
const artifact = { input: { transcript: 'Synthetic test memory, no customer data.' }, output: { title: 'Telemetry verification' }, usage: { input_tokens: 40, output_tokens: 20 }, testOnly: true };
await client.action(api.telemetry.record, { requestId, name: 'verification', status: 'succeeded', elapsedMs: 10, model: 'mock-no-api-cost', artifactJson: JSON.stringify(artifact) });
await client.mutation(api.telemetry.finish, { requestId, status: 'succeeded', httpStatus: 200, elapsedMs: 20 });
const latest = await client.query(api.telemetry.latestMine, {});
assert.equal(latest[0]._id, requestId);
assert.equal(latest[0].status, 'succeeded');
const events = await client.query(api.telemetry.eventsMine, { requestId });
assert.equal(events.length, 1);
assert.deepEqual(JSON.parse(await client.action(api.telemetry.artifactMine, { eventId: events[0]._id })), artifact);
const other = new ConvexHttpClient(url);
assert.deepEqual(await other.query(api.telemetry.latestMine, {}), []);
await assert.rejects(other.query(api.telemetry.eventsMine, { requestId }), /not found/);
await assert.rejects(other.action(api.telemetry.artifactMine, { eventId: events[0]._id }), /Sign in/);
const second = await other.action(api.auth.signIn, { provider: 'password', params: { flow: 'signUp', email: `telemetry-other-${randomUUID()}@example.invalid`, password: randomUUID() + randomUUID() } });
other.setAuth(second.tokens.token);
await assert.rejects(other.query(api.telemetry.eventsMine, { requestId }), /not found/);
await assert.rejects(other.action(api.telemetry.artifactMine, { eventId: events[0]._id }), /not found/);
await assert.rejects(other.mutation(api.telemetry.finish, { requestId, status: 'failed', elapsedMs: 1, httpStatus: 500 }), /not found/);
const failedRequestId = await client.mutation(api.telemetry.start, { generationId, stage: 'transcribe', promptVersion: 'verification-only' });
await client.action(api.telemetry.record, { requestId: failedRequestId, name: 'verification-failure', status: 'failed', elapsedMs: 10, artifactJson: JSON.stringify({ error: 'Synthetic provider failure', testOnly: true }) });
await client.mutation(api.telemetry.finish, { requestId: failedRequestId, status: 'failed', elapsedMs: 10, httpStatus: 500, error: 'Synthetic provider failure' });
assert.equal((await client.query(api.telemetry.latestMine, {}))[0].status, 'failed');
await client.mutation(api.telemetry.productEvent, { name: 'preview_ready', generationId, elapsedMs: 20 });
console.log('PASS: development database saved and returned exact JSON; recorded success/failure and user event; logged-out and second-user access refused. No AI calls made.');
